public class DataPribadi {
    public static void main(String[] args) {

        int umur = 20; // data umur
        double tinggi = 173; // data tinggi badan
        char golDarah = 'O'; // data golongan darah
        boolean mahasiswaAktif = true; // status mahasiswa

        // Menampilkan semua data
        System.out.println("Umur: " + umur + " tahun");
        System.out.println("Tinggi: " + tinggi + " cm");
        System.out.println("Golongan Darah: " + golDarah);
        System.out.println("Aktif: " + mahasiswaAktif);
    }
}
